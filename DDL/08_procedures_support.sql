-- Distancia em metros (Haversine). Usada pela sp_registrar_marcacao_ponto e pela DQL 04.
CREATE OR REPLACE FUNCTION fn_distance_meters(lat1 NUMERIC, lon1 NUMERIC, lat2 NUMERIC, lon2 NUMERIC)
RETURNS DOUBLE PRECISION LANGUAGE sql IMMUTABLE AS $$
    SELECT 2 * 6371000 * asin(sqrt(
        power(sin(radians((lat2 - lat1)::float8) / 2), 2) +
        cos(radians(lat1::float8)) * cos(radians(lat2::float8)) *
        power(sin(radians((lon2 - lon1)::float8) / 2), 2)))
$$;

-- ----------------------------------------------------------------------------
-- Fechamento mensal por colaborador / Monthly closing per employee
-- ----------------------------------------------------------------------------
CREATE TABLE timesheet_closings (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    employee_id       BIGINT   NOT NULL REFERENCES employees (id),
    apuration_period_id BIGINT NOT NULL REFERENCES apuration_periods (id),
    period_start      DATE     NOT NULL,
    period_end        DATE     NOT NULL,
    worked_minutes    INTEGER  NOT NULL,
    overtime_minutes  INTEGER  NOT NULL,   -- 50% + 100%
    night_minutes     INTEGER  NOT NULL,   -- adicional noturno
    absence_minutes   INTEGER  NOT NULL,
    absence_days      INTEGER  NOT NULL,   -- dias com day_status = ABSENCE
    status            VARCHAR(20) NOT NULL DEFAULT 'CLOSED' CHECK (status IN ('CLOSED')),
    closed_at         TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_by_user    BIGINT   NOT NULL REFERENCES users (id),
    integrity_hash    CHAR(64) NOT NULL,   -- SHA-256 dos totais (assinatura de integridade)
    CONSTRAINT ck_timesheet_closings_period CHECK (period_end >= period_start),
    CONSTRAINT ex_timesheet_closings_overlap
        EXCLUDE USING gist (employee_id WITH =, daterange(period_start, period_end, '[]') WITH &&)
);

-- Bloqueio: nenhuma alteracao em apuracao/marcacao de periodo fechado do colaborador.
CREATE OR REPLACE FUNCTION fn_block_closed_timesheet() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    v_employee BIGINT;
    v_date     DATE;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_employee := OLD.employee_id;
    ELSE
        v_employee := NEW.employee_id;
    END IF;

    IF TG_TABLE_NAME = 'daily_apurations' THEN
        v_date := CASE WHEN TG_OP = 'DELETE' THEN OLD.date ELSE NEW.date END;
    ELSE
        v_date := CASE WHEN TG_OP = 'DELETE' THEN OLD.punched_at::date ELSE NEW.punched_at::date END;
    END IF;

    IF EXISTS (SELECT 1 FROM timesheet_closings tc
               WHERE tc.employee_id = v_employee
                 AND v_date BETWEEN tc.period_start AND tc.period_end) THEN
        RAISE EXCEPTION 'Espelho de ponto fechado: colaborador % em % (% em %)',
            v_employee, v_date, TG_OP, TG_TABLE_NAME USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;

CREATE TRIGGER trg_daily_apurations_closed_lock
    BEFORE INSERT OR UPDATE OR DELETE ON daily_apurations
    FOR EACH ROW EXECUTE FUNCTION fn_block_closed_timesheet();
CREATE TRIGGER trg_time_punches_closed_lock
    BEFORE INSERT OR UPDATE OR DELETE ON time_punches
    FOR EACH ROW EXECUTE FUNCTION fn_block_closed_timesheet();

-- ----------------------------------------------------------------------------
-- Banco de horas / Hour bank
-- ----------------------------------------------------------------------------
CREATE TABLE hour_bank_movements (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    employee_id   BIGINT      NOT NULL REFERENCES employees (id),
    movement_date DATE        NOT NULL,
    movement_type VARCHAR(20) NOT NULL CHECK (movement_type IN ('OVERTIME_CREDIT','DAY_OFF_DEBIT')),
    minutes       INTEGER     NOT NULL CHECK (minutes > 0),
    source_daily_apuration_id BIGINT REFERENCES daily_apurations (id),
    notes         VARCHAR(255),
    created_at    TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_hour_bank_movements_emp_date ON hour_bank_movements (employee_id, movement_date);

CREATE TABLE hour_bank_balances (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    employee_id      BIGINT  NOT NULL REFERENCES employees (id),
    window_start     DATE    NOT NULL,
    window_end       DATE    NOT NULL,
    credit_minutes   INTEGER NOT NULL,
    debit_minutes    INTEGER NOT NULL,
    balance_minutes  INTEGER NOT NULL,   -- pode ser negativo
    recalculated_at  TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_hour_bank_balances UNIQUE (employee_id, window_start, window_end),
    CONSTRAINT ck_hour_bank_balances_window CHECK (window_end >= window_start)
);

