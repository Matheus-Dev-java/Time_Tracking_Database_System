-- Employers, departments and work locations.
CREATE TABLE employer (
    employer_id integer GENERATED BY DEFAULT AS IDENTITY,
    cnpj char(14) NOT NULL,
    legal_name varchar(150) NOT NULL,
    trade_name varchar(120) NOT NULL,
    CONSTRAINT pk_employer PRIMARY KEY (employer_id),
    CONSTRAINT uq_employer_cnpj UNIQUE (cnpj)
);

CREATE TABLE department (
    department_id integer GENERATED BY DEFAULT AS IDENTITY,
    employer_id integer NOT NULL,
    name varchar(60) NOT NULL,
    CONSTRAINT pk_department PRIMARY KEY (department_id),
    CONSTRAINT uq_department_employer_name UNIQUE (employer_id, name),
    CONSTRAINT fk_department_employer FOREIGN KEY (employer_id) REFERENCES employer (employer_id) ON DELETE RESTRICT
);

CREATE TABLE work_location (
    work_location_id integer GENERATED BY DEFAULT AS IDENTITY,
    employer_id integer NOT NULL,
    name varchar(80) NOT NULL,
    latitude numeric(10, 8) NOT NULL,
    longitude numeric(11, 8) NOT NULL,
    radius_meters integer NOT NULL,
    allowed_network cidr NOT NULL,
    CONSTRAINT pk_work_location PRIMARY KEY (work_location_id),
    CONSTRAINT uq_work_location_employer UNIQUE (employer_id, work_location_id),
    CONSTRAINT uq_work_location_employer_name UNIQUE (employer_id, name),
    CONSTRAINT fk_work_location_employer FOREIGN KEY (employer_id) REFERENCES employer (employer_id) ON DELETE RESTRICT
);

-- Employees and punch devices, both bound to the employer through composite keys.
CREATE TABLE employee (
    employee_id integer GENERATED BY DEFAULT AS IDENTITY,
    employer_id integer NOT NULL,
    department_id integer NOT NULL,
    job_title_id integer NOT NULL,
    work_location_id integer NOT NULL,
    name varchar(120) NOT NULL,
    cpf char(11) NOT NULL,
    pis char(11) NOT NULL,
    registration_number varchar(20) NOT NULL,
    hire_date date NOT NULL,
    termination_date date,
    active boolean NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_employee PRIMARY KEY (employee_id),
    CONSTRAINT uq_employee_employer UNIQUE (employer_id, employee_id),
    CONSTRAINT uq_employee_cpf UNIQUE (cpf),
    CONSTRAINT uq_employee_pis UNIQUE (pis),
    CONSTRAINT uq_employee_registration UNIQUE (employer_id, registration_number),
    CONSTRAINT fk_employee_work_location FOREIGN KEY (employer_id, work_location_id) REFERENCES work_location (employer_id, work_location_id) ON DELETE RESTRICT,
    CONSTRAINT fk_employee_department FOREIGN KEY (department_id) REFERENCES department (department_id) ON DELETE RESTRICT,
    CONSTRAINT fk_employee_job_title FOREIGN KEY (job_title_id) REFERENCES job_title (job_title_id) ON DELETE RESTRICT
);

CREATE TABLE device (
    device_id integer GENERATED BY DEFAULT AS IDENTITY,
    employer_id integer NOT NULL,
    work_location_id integer NOT NULL,
    device_type_id integer NOT NULL,
    serial_number varchar(36) NOT NULL,
    active boolean NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_device PRIMARY KEY (device_id),
    CONSTRAINT uq_device_employer UNIQUE (employer_id, device_id),
    CONSTRAINT uq_device_serial_number UNIQUE (serial_number),
    CONSTRAINT fk_device_work_location FOREIGN KEY (employer_id, work_location_id) REFERENCES work_location (employer_id, work_location_id) ON DELETE RESTRICT,
    CONSTRAINT fk_device_device_type FOREIGN KEY (device_type_id) REFERENCES device_type (device_type_id) ON DELETE RESTRICT
);

-- Work schedules, their weekdays and the schedule history of each employee.
CREATE TABLE work_schedule (
    work_schedule_id integer GENERATED BY DEFAULT AS IDENTITY,
    employer_id integer NOT NULL,
    name varchar(80) NOT NULL,
    daily_minutes integer NOT NULL,
    tolerance_minutes integer NOT NULL,
    CONSTRAINT pk_work_schedule PRIMARY KEY (work_schedule_id),
    CONSTRAINT uq_work_schedule_employer_name UNIQUE (employer_id, name),
    CONSTRAINT fk_work_schedule_employer FOREIGN KEY (employer_id) REFERENCES employer (employer_id) ON DELETE RESTRICT
);

CREATE TABLE work_schedule_day (
    work_schedule_day_id integer GENERATED BY DEFAULT AS IDENTITY,
    work_schedule_id integer NOT NULL,
    weekday integer NOT NULL,
    day_off boolean NOT NULL,
    entry_time time,
    break_start_time time,
    break_end_time time,
    exit_time time,
    CONSTRAINT pk_work_schedule_day PRIMARY KEY (work_schedule_day_id),
    CONSTRAINT uq_work_schedule_day UNIQUE (work_schedule_id, weekday),
    CONSTRAINT fk_work_schedule_day_work_schedule FOREIGN KEY (work_schedule_id) REFERENCES work_schedule (work_schedule_id) ON DELETE CASCADE
);

CREATE TABLE employee_schedule_history (
    employee_schedule_history_id integer GENERATED BY DEFAULT AS IDENTITY,
    employee_id integer NOT NULL,
    work_schedule_id integer NOT NULL,
    start_date date NOT NULL,
    end_date date,
    CONSTRAINT pk_employee_schedule_history PRIMARY KEY (employee_schedule_history_id),
    CONSTRAINT fk_employee_schedule_history_employee FOREIGN KEY (employee_id) REFERENCES employee (employee_id) ON DELETE RESTRICT,
    CONSTRAINT fk_employee_schedule_history_work_schedule FOREIGN KEY (work_schedule_id) REFERENCES work_schedule (work_schedule_id) ON DELETE RESTRICT
);

-- Punches, always with latitude, longitude and an IP address.
CREATE TABLE time_punch (
    time_punch_id integer GENERATED BY DEFAULT AS IDENTITY,
    employer_id integer NOT NULL,
    employee_id integer NOT NULL,
    device_id integer NOT NULL,
    punch_type_id integer NOT NULL,
    sequence_number bigint NOT NULL,
    punched_at timestamp NOT NULL,
    latitude numeric(10, 8) NOT NULL,
    longitude numeric(11, 8) NOT NULL,
    ip_address inet NOT NULL,
    outside_perimeter boolean NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_time_punch PRIMARY KEY (time_punch_id),
    CONSTRAINT uq_time_punch_sequence_number UNIQUE (sequence_number),
    CONSTRAINT fk_time_punch_employee FOREIGN KEY (employer_id, employee_id) REFERENCES employee (employer_id, employee_id) ON DELETE RESTRICT,
    CONSTRAINT fk_time_punch_device FOREIGN KEY (employer_id, device_id) REFERENCES device (employer_id, device_id) ON DELETE RESTRICT,
    CONSTRAINT fk_time_punch_punch_type FOREIGN KEY (punch_type_id) REFERENCES punch_type (punch_type_id) ON DELETE RESTRICT
);

